ink_epd_region_t ink_epd_ui_usb_msc_popup_region(void) {
  return (ink_epd_region_t){.x = USB_MSC_REGION_X,
                            .y = USB_MSC_REGION_Y,
                            .width = USB_MSC_REGION_WIDTH,
                            .height = USB_MSC_REGION_HEIGHT};
}

void ink_epd_ui_draw_usb_msc_popup(uint8_t *buffer, size_t length,
                                   ink_epd_ui_usb_msc_popup_t popup) {
  if (!buffer || length < INK_EPD_BUFFER_SIZE) return;
  ink_epd_ui_fill_rect(buffer, length, USB_MSC_REGION_X, USB_MSC_REGION_Y,
                       USB_MSC_REGION_WIDTH, USB_MSC_REGION_HEIGHT, false);
  const uint8_t *image = popup == INK_EPD_UI_USB_MSC_FAILED
                             ? kUsbMscFailed
                             : kUsbMscActive;
  for (int y = 0; y < USB_MSC_IMAGE_HEIGHT; ++y) {
    for (int x = 0; x < USB_MSC_IMAGE_WIDTH; ++x) {
      const uint8_t mask = (uint8_t)(0x80U >> (x & 7));
      const bool black =
          (image[y * USB_MSC_IMAGE_ROW_BYTES + x / 8] & mask) != 0U;
      ink_epd_ui_set_pixel(buffer, length, USB_MSC_IMAGE_X + x,
                           USB_MSC_IMAGE_Y + y, black);
    }
  }
}
