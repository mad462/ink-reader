_Static_assert(sizeof(kLoadingImage) ==
                   LOADING_IMAGE_ROW_BYTES * LOADING_IMAGE_HEIGHT,
               "loading image size");

ink_epd_region_t ink_epd_ui_loading_region(void) {
  return (ink_epd_region_t){
      .x = LOADING_REGION_X,
      .y = LOADING_REGION_Y,
      .width = LOADING_REGION_WIDTH,
      .height = LOADING_REGION_HEIGHT,
  };
}

void ink_epd_ui_draw_loading(uint8_t *buffer, size_t length) {
  if (!buffer || length < INK_EPD_BUFFER_SIZE) return;

  ink_epd_ui_fill_rect(buffer, length, LOADING_REGION_X, LOADING_REGION_Y,
                       LOADING_REGION_WIDTH, LOADING_REGION_HEIGHT, false);
  for (int y = 0; y < LOADING_IMAGE_HEIGHT; ++y) {
    for (int x = 0; x < LOADING_IMAGE_WIDTH; ++x) {
      const uint8_t byte =
          kLoadingImage[y * LOADING_IMAGE_ROW_BYTES + x / 8];
      if (byte & (uint8_t)(0x80U >> (x & 7)))
        ink_epd_ui_set_pixel(buffer, length, LOADING_IMAGE_X + x,
                             LOADING_IMAGE_Y + y, true);
    }
  }
}
